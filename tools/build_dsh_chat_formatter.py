"""Build an offline renderer note from integrity-checked, pinned MIT distributions."""
import argparse
import base64
import hashlib
import io
import json
from pathlib import Path
import tarfile
import urllib.request

ROOT = Path(__file__).resolve().parents[1]
VENDOR = ROOT / 'customizations/vendor/dsh-chat-markdown'
PACKAGES = [('katex', '0.19.1', 'dist/katex.min.js'), ('markdown-it', '15.0.3', 'dist/browser/markdown-it.umd.min.js')]

def vendor():
    VENDOR.mkdir(parents=True, exist_ok=True)
    records = []
    for name, version, distribution in PACKAGES:
        with urllib.request.urlopen(f'https://registry.npmjs.org/{name}/{version}', timeout=30) as response: metadata = json.load(response)
        if metadata['license'] != 'MIT': raise RuntimeError(f'Unexpected license: {name}')
        with urllib.request.urlopen(metadata['dist']['tarball'], timeout=30) as response: archive = response.read()
        integrity = 'sha512-' + base64.b64encode(hashlib.sha512(archive).digest()).decode()
        if integrity != metadata['dist']['integrity']: raise RuntimeError(f'Integrity mismatch: {name}')
        with tarfile.open(fileobj=io.BytesIO(archive), mode='r:gz') as tar:
            script = tar.extractfile('package/' + distribution).read()
            candidates = ['package/LICENSE', 'package/LICENSE.txt', 'package/license.txt']
            license_name = next(path for path in candidates if path in tar.getnames())
            license_text = tar.extractfile(license_name).read()
        (VENDOR / f'{name}.min.js').write_bytes(script)
        (VENDOR / f'{name}-LICENSE.txt').write_bytes(license_text)
        records.append({'name': name, 'version': version, 'license': 'MIT', 'source': metadata['dist']['tarball'], 'integrity': integrity, 'scriptSha256': hashlib.sha256(script).hexdigest()})
    (VENDOR / 'manifest.json').write_text(json.dumps(records, indent=2) + '\n', encoding='utf-8')

def build():
    records = json.loads((VENDOR / 'manifest.json').read_text(encoding='utf-8'))
    parts = ['// Generated by tools/build_dsh_chat_formatter.py; MIT notices in vendor/dsh-chat-markdown/.\n']
    for name, _, _ in PACKAGES:
        data = (VENDOR / f'{name}.min.js').read_bytes()
        record = next(record for record in records if record['name'] == name)
        if hashlib.sha256(data).hexdigest() != record['scriptSha256']: raise RuntimeError(f'Vendored script modified: {name}')
        identifier = 'katex' if name == 'katex' else 'MarkdownIt'
        parts.append(f'const {identifier} = (() => {{ const module = {{ exports: {{}} }}; const exports = module.exports;\n')
        parts.append(data.decode('utf-8'))
        parts.append('\nreturn module.exports; })();\n')
    parts.append((ROOT / 'customizations/frontend/dsh-chat-format.js').read_text(encoding='utf-8'))
    parts.append('\nreturn createDshFormatter(MarkdownIt, katex);\n')
    output = ROOT / 'customizations/frontend/dsh-chat-format.bundle.js'
    output.write_text(''.join(parts), encoding='utf-8')
    print(f'Built offline renderer ({output.stat().st_size} bytes)')

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--vendor', action='store_true', help='Fetch the pinned distributions; normal builds are offline')
    args = parser.parse_args()
    if args.vendor: vendor()
    build()
