const assert = require('node:assert/strict');
const vm = require('node:vm');
const fs = require('node:fs');
let serial = 0;
let persisted = JSON.stringify({ version: 1, revision: 0, tasks: [], events: [] });
const source = fs.readFileSync('customizations/backend/commission-service.js', 'utf8');
const sandbox = { api: {
    getNote: id => id === 'MyoQuestData' ? { hasLabel: () => true, getContent: () => persisted, setContent: value => { persisted = value; } } : id === 'existingNote' ? {} : null,
    randomString: () => 'testId' + (++serial)
}};
vm.createContext(sandbox);
vm.runInContext(source + ';this.service = commissionService;', sandbox);
const call = (action, payload = {}) => sandbox.service(action, payload);
const input = { title: '学习模电', description: '理解一个知识点', coins: 12, xp: 40, skill: '模拟电路', itemName: '一级补给箱', itemQuantity: 1, noteLink: '#root/existingNote' };
let state = call('create', { ...input, revision: 0 });
const id = state.tasks[0].id;
assert.equal(state.tasks[0].noteId, 'existingNote');
state = call('complete', { id, revision: 1 });
assert.equal(state.wallet.coins, 12); assert.equal(state.wallet.xp, 40); assert.equal(state.wallet.skills['模拟电路'],40);
assert.equal(state.wallet.items['一级补给箱'], 1);
state = call('complete', { id, revision: 1 });
assert.equal(state.events.length, 1, 'duplicate completion must not double reward');
assert.throws(() => call('edit', { ...input, id, revision: state.revision }), /撤销/);
state = call('undo', { id, revision: state.revision });
assert.equal(state.wallet.coins, 0); assert.equal(state.wallet.items['一级补给箱'], 0);
assert.equal(state.events.length, 2);
state = call('undo', { id, revision: state.revision - 1 });
assert.equal(state.events.length, 2, 'duplicate undo must not double deduct');
assert.throws(() => call('edit', { ...input, id, revision: 0 }), /另一窗口/);
assert.throws(() => call('edit', { ...input, coins: -1, id, revision: state.revision }), /整数/);
assert.throws(() => call('edit', { ...input, itemQuantity: 0, id, revision: state.revision }), /至少/);
assert.throws(() => call('edit', { ...input, noteLink: 'javascript:alert(1)', id, revision: state.revision }), /链接/);
state = call('edit', { ...input, coins: 20, id, revision: state.revision });
state = call('complete', { id, revision: state.revision });
assert.equal(state.wallet.coins, 20); assert.equal(state.events.length, 3);
state = call('archive', { id, revision: state.revision });
assert.equal(state.tasks[0].archived, true); assert.equal(state.wallet.coins, 20);
state = call('restore', { id, revision: state.revision });
assert.equal(state.tasks[0].archived, false);
assert.equal(call('load').wallet.coins, 20, 'state survives reload');
state = call('create', { ...input, skill: '__proto__', itemName: '__proto__', revision: state.revision });
state = call('complete', { id: state.tasks[0].id, revision: state.revision });
assert.equal(state.wallet.items['__proto__'], 1, 'arbitrary item names are safe');
const before = persisted;
assert.throws(() => call('create', { ...input, title: '', revision: state.revision }), /不能为空/);
assert.equal(persisted, before, 'invalid operation does not persist changes');
const originalTaskId = id;
state = call('productCreate', { name: '休息券', description: '休息 30 分钟', category: '休息', price: 5, revision: state.revision });
const productId = state.products[0].id;
const buyRevision = state.revision;
state = call('buy', { id: productId, quantity: 2, revision: buyRevision });
assert.equal(state.wallet.coins, 22); assert.equal(state.wallet.items['休息券'], 2);
assert.throws(() => call('buy', {id:productId,quantity:2,revision:buyRevision}), /另一窗口/);
assert.equal(call('load').wallet.items['休息券'], 2, 'stale purchase does not duplicate');
let snapshot = persisted;
assert.throws(()=>call('buy',{id:productId,quantity:999,revision:state.revision}), /金币不足/);
assert.equal(persisted,snapshot);
assert.throws(()=>call('buy',{id:productId,quantity:0,revision:state.revision}), /至少/);
assert.throws(()=>call('buy',{id:productId,quantity:1.5,revision:state.revision}), /整数/);
state=call('productEdit',{id:productId,name:'休息券新版',description:'新说明',category:'休息',price:6,revision:state.revision});
assert.equal(state.wallet.items['休息券'],2,'editing preserves purchased inventory');
assert.equal(state.events.find(event=>event.kind==='purchase').unitPrice,5);
state=call('useItem',{itemName:'休息券',quantity:1,revision:state.revision});
assert.equal(state.wallet.items['休息券'],1);
assert.throws(()=>call('useItem',{itemName:'休息券',quantity:2,revision:state.revision}),/不足/);
state=call('productArchive',{id:productId,revision:state.revision});
assert.throws(()=>call('buy',{id:productId,quantity:1,revision:state.revision}),/下架/);
state=call('productRestore',{id:productId,revision:state.revision});
state=call('buy',{id:productId,quantity:1,revision:state.revision});
assert.equal(state.wallet.items['休息券新版'],1);
assert.throws(()=>call('undo',{id:originalTaskId,revision:state.revision}),/奖励已使用/);
state=call('useItem',{itemName:'一级补给箱',quantity:1,revision:state.revision});
assert.equal(state.wallet.items['一级补给箱'],0,'quest item is usable');
state=call('productCreate',{name:'__proto__',category:'道具',description:'',price:0,revision:state.revision});
state=call('buy',{id:state.products[0].id,quantity:1,revision:state.revision});
assert.equal(state.wallet.items['__proto__'],2);
assert.equal(call('load').products.length,2);
snapshot = persisted;
assert.throws(()=>call('productCreate',{name:'',price:1,revision:state.revision}),/不能为空/);
assert.equal(persisted,snapshot);
// Loading older data adds the optional catalog only to the view, not to stored data.
const legacy = JSON.parse(persisted); delete legacy.products; persisted=JSON.stringify(legacy);
assert.equal(call('load').products.length,0); assert.equal(JSON.parse(persisted).products,undefined);
assert.equal(call('load').wallet.coins,16,'legacy migration retains ledger balances');
persisted = '{bad';
assert.throws(() => call('load'), /损坏/);
assert.equal(persisted, '{bad', 'corrupt state is never reset automatically');
console.log('PASS: quests, shop CRUD, purchase, warehouse usage, historical snapshots, conflicts, balances, legacy migration, corrupt data protection');
